//! BENCHMARK-ONLY prototype of "Option A": a multiplexing, auto-pipelining
//! RESP proxy placed in front of a single Valkey primary.
//!
//! This exists to measure whether the architecture can beat a tuned Valkey on
//! the same cores. It is intentionally incomplete and must not be deployed:
//! no TLS, no AUTH/ACL passthrough, no cluster routing, no RESP3, and every
//! connection-scoped command is refused (see `is_connection_scoped`).
//!
//! Data path:
//!   client socket -> client reader task -> bounded mpsc -> upstream writer
//!   (drains the queue into one write) -> Valkey -> upstream reader (splits
//!   replies per batch) -> per-client channel -> client writer task.
//!
//! Each client is pinned to one upstream connection, so per-client reply
//! order is preserved by the upstream FIFO.

use std::collections::VecDeque;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Duration;

use bytes::{Bytes, BytesMut};
use resp_common::{parse_reply_from, parse_request_from, Request};
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::tcp::{OwnedReadHalf, OwnedWriteHalf};
use tokio::net::{TcpListener, TcpStream};
use tokio::sync::{mpsc, Notify, Semaphore};

/// Max commands a single client may have in flight before the proxy stops
/// reading its socket. Bounds per-client memory and applies backpressure.
const MAX_CLIENT_INFLIGHT: usize = 1024;
/// Bounded queue between client readers and each upstream writer.
const UPSTREAM_QUEUE: usize = 8192;
/// Upper bound on bytes coalesced into one upstream write.
const MAX_UPSTREAM_BATCH_BYTES: usize = 256 * 1024;

struct Counters {
    clients_accepted: AtomicU64,
    commands_forwarded: AtomicU64,
    commands_refused: AtomicU64,
    upstream_writes: AtomicU64,
    upstream_reconnects: AtomicU64,
    client_protocol_errors: AtomicU64,
}

static STATS: Counters = Counters {
    clients_accepted: AtomicU64::new(0),
    commands_forwarded: AtomicU64::new(0),
    commands_refused: AtomicU64::new(0),
    upstream_writes: AtomicU64::new(0),
    upstream_reconnects: AtomicU64::new(0),
    client_protocol_errors: AtomicU64::new(0),
};

/// Replies delivered to a client writer: the bytes plus how many commands they
/// answer (to release in-flight permits). `Err` tells the writer to close.
type ClientMsg = Result<(Bytes, u32), ()>;

struct Batch {
    /// Encoded commands to forward; empty for a locally generated reply.
    payload: Bytes,
    /// Number of upstream replies that answer `payload`.
    replies: u32,
    /// Reply generated by the proxy itself (refused command).
    local_reply: Option<Bytes>,
    reply_to: mpsc::UnboundedSender<ClientMsg>,
}

struct Pending {
    replies: u32,
    done: u32,
    scan: usize,
    local_reply: Option<Bytes>,
    reply_to: mpsc::UnboundedSender<ClientMsg>,
}

/// Commands whose effect is scoped to a connection (or that change the number
/// of replies per request). Forwarding them over a shared upstream connection
/// would leak state between clients or desynchronize reply accounting.
fn is_connection_scoped(name: &[u8]) -> bool {
    const DENY: &[&[u8]] = &[
        b"AUTH", b"HELLO", b"SELECT", b"CLIENT", b"RESET", b"QUIT", b"MULTI", b"EXEC", b"DISCARD",
        b"WATCH", b"UNWATCH", b"SUBSCRIBE", b"PSUBSCRIBE", b"SSUBSCRIBE", b"UNSUBSCRIBE",
        b"PUNSUBSCRIBE", b"SUNSUBSCRIBE", b"MONITOR", b"BLPOP", b"BRPOP", b"BLMOVE", b"BRPOPLPUSH",
        b"BLMPOP", b"BZPOPMIN", b"BZPOPMAX", b"BZMPOP", b"XREAD", b"XREADGROUP", b"WAIT", b"WAITAOF",
        b"READONLY", b"READWRITE", b"ASKING", b"SYNC", b"PSYNC", b"REPLCONF",
    ];
    DENY.iter().any(|d| d.eq_ignore_ascii_case(name))
}

struct Args {
    listen: String,
    upstream: String,
    upstream_conns: usize,
    threads: usize,
}

fn parse_args() -> Args {
    let mut a = Args { listen: "127.0.0.1:7000".into(), upstream: "127.0.0.1:6379".into(), upstream_conns: 4, threads: 1 };
    let v: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i + 1 < v.len() {
        match v[i].as_str() {
            "--listen" => a.listen = v[i + 1].clone(),
            "--upstream" => a.upstream = v[i + 1].clone(),
            "--upstream-conns" => a.upstream_conns = v[i + 1].parse().expect("--upstream-conns"),
            "--threads" => a.threads = v[i + 1].parse().expect("--threads"),
            other => panic!("unknown argument {other}"),
        }
        i += 2;
    }
    assert!(a.upstream_conns > 0 && a.threads > 0);
    a
}

/// Owns one upstream connection; reconnects with backoff on failure. Batches
/// received while disconnected stay queued (bounded) until reconnection.
async fn upstream_task(addr: String, mut rx: mpsc::Receiver<Batch>) {
    let mut backoff = Duration::from_millis(50);
    loop {
        let sock = match TcpStream::connect(&addr).await {
            Ok(s) => s,
            Err(e) => {
                eprintln!("proxy: upstream connect {addr}: {e}");
                tokio::time::sleep(backoff).await;
                backoff = (backoff * 2).min(Duration::from_secs(1));
                continue;
            }
        };
        backoff = Duration::from_millis(50);
        let _ = sock.set_nodelay(true);
        let (rd, wr) = sock.into_split();
        let (ptx, prx) = mpsc::unbounded_channel::<Pending>();
        let stop = Arc::new(Notify::new());
        let mut reader = tokio::spawn(upstream_reader(rd, prx, stop.clone()));
        let mut reader_done = false;
        let res = tokio::select! {
            r = upstream_writer(wr, &mut rx, ptx) => r,
            r = &mut reader => {
                reader_done = true;
                match r {
                    Ok(Err(e)) => Err(e),
                    _ => Err("upstream reader stopped".into()),
                }
            }
        };
        if res.is_ok() {
            return; // every client sender is gone: shutting down
        }
        if !reader_done {
            stop.notify_one();
            let _ = reader.await;
        }
        eprintln!("proxy: upstream {addr} failed: {}; reconnecting", res.unwrap_err());
        STATS.upstream_reconnects.fetch_add(1, Ordering::Relaxed);
    }
}

async fn upstream_writer(
    mut wr: OwnedWriteHalf,
    rx: &mut mpsc::Receiver<Batch>,
    ptx: mpsc::UnboundedSender<Pending>,
) -> Result<(), String> {
    let mut buf = BytesMut::with_capacity(MAX_UPSTREAM_BATCH_BYTES);
    loop {
        let Some(first) = rx.recv().await else { return Ok(()) };
        // tokio runs a freshly woken task next (LIFO slot), which would flush
        // after every single request. Yield once so the other ready client
        // tasks enqueue first and the drain below sees a real batch.
        tokio::task::yield_now().await;
        let mut next = Some(first);
        buf.clear();
        // Auto-pipelining: drain whatever is already queued into one write.
        while let Some(b) = next.take() {
            buf.extend_from_slice(&b.payload);
            STATS.commands_forwarded.fetch_add(b.replies as u64, Ordering::Relaxed);
            let p = Pending { replies: b.replies, done: 0, scan: 0, local_reply: b.local_reply, reply_to: b.reply_to };
            // Registered before the bytes are written, so the reader always
            // knows who a reply belongs to.
            ptx.send(p).map_err(|_| "upstream reader gone")?;
            if buf.len() < MAX_UPSTREAM_BATCH_BYTES {
                next = rx.try_recv().ok();
            }
        }
        if !buf.is_empty() {
            wr.write_all(&buf).await.map_err(|e| format!("write: {e}"))?;
            STATS.upstream_writes.fetch_add(1, Ordering::Relaxed);
        }
    }
}

/// Splits upstream replies back into per-batch chunks. On any failure every
/// in-flight request is failed: its outcome is unknown, and a generic proxy
/// cannot know whether a command is safe to retry.
async fn upstream_reader(rd: OwnedReadHalf, mut prx: mpsc::UnboundedReceiver<Pending>, stop: Arc<Notify>) -> Result<(), String> {
    let mut pending: VecDeque<Pending> = VecDeque::new();
    let r = upstream_reader_loop(rd, &mut prx, &mut pending, &stop).await;
    if r.is_err() {
        prx.close();
        while let Ok(p) = prx.try_recv() {
            pending.push_back(p);
        }
        for p in pending.drain(..) {
            let _ = p.reply_to.send(Err(()));
        }
    }
    r
}

async fn upstream_reader_loop(
    mut rd: OwnedReadHalf,
    prx: &mut mpsc::UnboundedReceiver<Pending>,
    pending: &mut VecDeque<Pending>,
    stop: &Notify,
) -> Result<(), String> {
    let mut buf = BytesMut::with_capacity(64 * 1024);
    let mut prx_open = true;
    loop {
        while let Ok(p) = prx.try_recv() {
            pending.push_back(p);
        }
        // Complete as many head entries as the buffered bytes allow.
        while let Some(head) = pending.front_mut() {
            if let Some(local) = head.local_reply.take() {
                let _ = head.reply_to.send(Ok((local, 1)));
                pending.pop_front();
                continue;
            }
            while head.done < head.replies {
                match parse_reply_from(&buf, head.scan).map_err(|e| e.to_string())? {
                    Some((end, _)) => {
                        head.scan = end;
                        head.done += 1;
                    }
                    None => break,
                }
            }
            if head.done < head.replies {
                break;
            }
            let chunk = buf.split_to(head.scan).freeze();
            let _ = head.reply_to.send(Ok((chunk, head.replies)));
            pending.pop_front();
        }
        if pending.is_empty() && !buf.is_empty() {
            return Err("reply received with no pending request".into());
        }
        if !prx_open && pending.is_empty() {
            return Ok(());
        }
        buf.reserve(16 * 1024);
        tokio::select! {
            biased;
            p = prx.recv(), if prx_open => match p {
                Some(p) => pending.push_back(p),
                None => prx_open = false,
            },
            r = rd.read_buf(&mut buf) => match r {
                Ok(0) => return Err("upstream closed".into()),
                Ok(_) => {}
                Err(e) => return Err(format!("read: {e}")),
            },
            _ = stop.notified() => return Err("stopped by writer failure".into()),
        }
    }
}

async fn client_writer(mut wr: OwnedWriteHalf, mut rx: mpsc::UnboundedReceiver<ClientMsg>, permits: Arc<Semaphore>) {
    let mut out = BytesMut::with_capacity(16 * 1024);
    while let Some(first) = rx.recv().await {
        out.clear();
        let mut released = 0u32;
        let mut close = false;
        let mut next = Some(first);
        // Coalesce every reply already available into one write.
        while let Some(m) = next.take() {
            match m {
                Ok((b, n)) => {
                    out.extend_from_slice(&b);
                    released += n;
                }
                Err(()) => {
                    close = true;
                    break;
                }
            }
            if out.len() < 256 * 1024 {
                next = rx.try_recv().ok();
            }
        }
        if !out.is_empty() && wr.write_all(&out).await.is_err() {
            return;
        }
        permits.add_permits(released as usize);
        if close {
            let _ = wr.shutdown().await;
            return;
        }
    }
}

const REFUSED: &[u8] = b"-ERR command not supported through proxy-poc (connection-scoped)\r\n";

async fn client_task(sock: TcpStream, upstream: mpsc::Sender<Batch>) {
    let _ = sock.set_nodelay(true);
    let (mut rd, wr) = sock.into_split();
    let (tx, rx) = mpsc::unbounded_channel::<ClientMsg>();
    let permits = Arc::new(Semaphore::new(MAX_CLIENT_INFLIGHT));
    tokio::spawn(client_writer(wr, rx, permits.clone()));

    // Invariant: buf[..pos] holds `batch_cmds` complete, not yet forwarded
    // commands; everything before them has been consumed.
    let mut buf = BytesMut::with_capacity(16 * 1024);
    let mut pos = 0usize;
    let mut batch_cmds = 0u32;
    loop {
        match rd.read_buf(&mut buf).await {
            Ok(0) | Err(_) => return,
            Ok(_) => {}
        }
        loop {
            let req = match parse_request_from(&buf, pos) {
                Ok(Some(r)) => r,
                Ok(None) => break,
                Err(_) => {
                    STATS.client_protocol_errors.fetch_add(1, Ordering::Relaxed);
                    return;
                }
            };
            match req {
                Request::Command { end, name, .. } if !is_connection_scoped(&buf[name.0..name.1]) => {
                    pos = end;
                    batch_cmds += 1;
                    if batch_cmds as usize == MAX_CLIENT_INFLIGHT && !forward(&mut buf, &mut pos, &mut batch_cmds, &upstream, &tx, &permits).await {
                        return;
                    }
                }
                Request::Command { end, .. } | Request::Empty { end } => {
                    let refused = matches!(req, Request::Command { .. });
                    let req_len = end - pos;
                    if batch_cmds > 0 && !forward(&mut buf, &mut pos, &mut batch_cmds, &upstream, &tx, &permits).await {
                        return;
                    }
                    let _ = buf.split_to(req_len);
                    // Valkey sends no reply for an empty multibulk, so it is
                    // dropped rather than forwarded as a counted command.
                    if refused {
                        STATS.commands_refused.fetch_add(1, Ordering::Relaxed);
                        let Ok(p) = permits.clone().acquire_many_owned(1).await else { return };
                        p.forget();
                        let b = Batch { payload: Bytes::new(), replies: 0, local_reply: Some(Bytes::from_static(REFUSED)), reply_to: tx.clone() };
                        if upstream.send(b).await.is_err() {
                            return;
                        }
                    }
                }
            }
        }
        if batch_cmds > 0 && !forward(&mut buf, &mut pos, &mut batch_cmds, &upstream, &tx, &permits).await {
            return;
        }
    }
}

/// Sends the `batch_cmds` commands in `buf[..pos]` upstream.
async fn forward(
    buf: &mut BytesMut,
    pos: &mut usize,
    batch_cmds: &mut u32,
    upstream: &mpsc::Sender<Batch>,
    tx: &mpsc::UnboundedSender<ClientMsg>,
    permits: &Arc<Semaphore>,
) -> bool {
    let Ok(p) = permits.clone().acquire_many_owned(*batch_cmds).await else { return false };
    p.forget();
    let payload = buf.split_to(*pos).freeze();
    let b = Batch { payload, replies: *batch_cmds, local_reply: None, reply_to: tx.clone() };
    *pos = 0;
    *batch_cmds = 0;
    upstream.send(b).await.is_ok()
}

async fn report_stats() {
    let mut iv = tokio::time::interval(Duration::from_secs(5));
    loop {
        iv.tick().await;
        print_stats();
    }
}

fn print_stats() {
    let fwd = STATS.commands_forwarded.load(Ordering::Relaxed);
    let writes = STATS.upstream_writes.load(Ordering::Relaxed).max(1);
    eprintln!(
        "proxy-stats clients_accepted={} commands_forwarded={} commands_refused={} upstream_writes={} avg_cmds_per_upstream_write={:.2} upstream_reconnects={} client_protocol_errors={}",
        STATS.clients_accepted.load(Ordering::Relaxed),
        fwd,
        STATS.commands_refused.load(Ordering::Relaxed),
        STATS.upstream_writes.load(Ordering::Relaxed),
        fwd as f64 / writes as f64,
        STATS.upstream_reconnects.load(Ordering::Relaxed),
        STATS.client_protocol_errors.load(Ordering::Relaxed),
    );
}

fn main() {
    let args = parse_args();
    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(args.threads)
        .enable_all()
        .build()
        .expect("runtime");
    rt.block_on(async move {
        let mut ups = Vec::new();
        for _ in 0..args.upstream_conns {
            let (tx, rx) = mpsc::channel::<Batch>(UPSTREAM_QUEUE);
            tokio::spawn(upstream_task(args.upstream.clone(), rx));
            ups.push(tx);
        }
        let listener = TcpListener::bind(&args.listen).await.expect("bind");
        eprintln!("proxy-poc listening on {} -> {} ({} upstream conns, {} threads)", args.listen, args.upstream, args.upstream_conns, args.threads);
        tokio::spawn(report_stats());
        let mut next = 0usize;
        loop {
            tokio::select! {
                r = listener.accept() => {
                    let Ok((sock, _)) = r else { continue };
                    STATS.clients_accepted.fetch_add(1, Ordering::Relaxed);
                    let up = ups[next % ups.len()].clone();
                    next += 1;
                    tokio::spawn(client_task(sock, up));
                }
                _ = tokio::signal::ctrl_c() => {
                    print_stats();
                    std::process::exit(0);
                }
            }
        }
    });
}
